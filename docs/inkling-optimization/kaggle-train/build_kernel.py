#!/usr/bin/env python3
"""Build the self-contained kaggle kernel.py: every payload script + hy4_id2cid
embedded as gz+b64; tokenizer.json fetched inside the instance from HF.
Run from repo root: python3 kaggle-train/build_kernel.py"""
import base64, gzip, glob, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'kernel.py')


def pack(path):
    return base64.b64encode(gzip.compress(open(path, 'rb').read(), 9)).decode()


def main():
    blobs = {}
    for f in sorted(glob.glob(os.path.join(HERE, 'payload', '*.py'))):
        name = os.path.basename(f)
        if name == 'kernel_main.py':
            continue
        blobs[name] = pack(f)
    id2cid = pack('/Users/sonder/dageno-modelbench/hy4_id2cid.npy')
    main_src = open(os.path.join(HERE, 'payload', 'kernel_main.py')).read()

    header = '''"""Self-contained kaggle kernel: Inkling-2-Mini engram graft training.
Generated by build_kernel.py - edit payload/ scripts and rebuild, do not edit here.

Phases (all work inside /kaggle/working, resumable across restarts):
 0. extract embedded scripts + id2cid map, download hy4 tokenizer from HF
 1. download official checkpoint from HF (public, fast on kaggle net)
 2. convert NVFP4/MXFP8 experts -> bf16 (cpu, chunked)
 3. fp16 engram tables via HTTP range streaming (HF mirror first, modelscope fallback)
 4. Muon adapter training, backbone frozen in NF4 (T4 x2 compatible)
"""
import base64, gzip, os, sys, json, shutil, subprocess, time

WORK = '/kaggle/working'
os.makedirs(WORK, exist_ok=True)

BLOBS = '''
    lines = [header]
    lines.append('{\n')
    for name, blob in blobs.items():
        lines.append(f'    {name!r}:\n        {blob!r},\n')
    lines.append('}\n\n')
    lines.append(f'ID2CID_B64 = {id2cid!r}\n\n')
    lines.append('''def extract():
    for name, blob in BLOBS.items():
        dst = os.path.join(WORK, name)
        if not os.path.exists(dst):
            with open(dst, 'wb') as f:
                f.write(gzip.decompress(base64.b64decode(blob)))
    with open(os.path.join(WORK, 'hy4_id2cid.npy'), 'wb') as f:
        f.write(gzip.decompress(base64.b64decode(ID2CID_B64)))
    sys.path.insert(0, WORK)

def fetch_tokenizer():
    dst = os.path.join(WORK, 'hy4-tokenizer.json')
    if os.path.exists(dst):
        return dst
    try:
        from huggingface_hub import hf_hub_download
        p = hf_hub_download('Tencent-Hunyuan/Hy4-flash', 'tokenizer.json')
        shutil.copy(p, dst)
        return dst
    except Exception as e:
        print('hf tokenizer failed:', e, flush=True)
    import requests
    url = 'https://modelscope.cn/api/v1/models/Tencent-Hunyuan/Hy4-flash/repo?FilePath=tokenizer.json'
    r = requests.get(url, timeout=60)
    r.raise_for_status()
    with open(dst, 'wb') as f:
        f.write(r.content)
    return dst

''')
    # append the kernel_main logic as a module body (its INPUT references are replaced)
    lines.append('''
extract()
fetch_tokenizer()

# install runtime deps the stock kaggle image lacks
subprocess.run([sys.executable, '-m', 'pip', 'install', '-q',
                'transformers>=5.24', 'tokenizers', 'safetensors', 'datasets', 'bitsandbytes', 'liger-kernel'],
               check=False)

''')
    # kernel_main body: strip INPUT-dependent staging (self-contained now)
    body = main_src.replace("INPUT = '/kaggle/input'", "INPUT = WORK")
    # drop its own extract-related lines that stage from input datasets
    lines.append(body)
    open(OUT, 'w').write(''.join(lines))
    print(f'kernel.py written: {os.path.getsize(OUT)/1024:.0f} KB')


if __name__ == '__main__':
    main()
